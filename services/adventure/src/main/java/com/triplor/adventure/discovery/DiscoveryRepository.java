package com.triplor.adventure.discovery;

import java.sql.Array;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

import com.triplor.adventure.discovery.DiscoveryDtos.AdventureCard;
import com.triplor.adventure.place.PlaceResponse;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;

/**
 * The read queries behind discovery. They are native SQL because they use what the ORM does
 * not model: the PostGIS {@code geography} column and the {@code daterange} column, both
 * generated by the database and both indexed with GiST.
 *
 * <p>Columns are selected by name. {@code location} and {@code trip_dates} are only filtered
 * on, never read into Java.
 */
@Repository
public class DiscoveryRepository {

    private static final String CARD_COLUMNS = """
            a.id, a.organizer_id, a.start_date, a.end_date, a.styles, a.description, a.capacity, a.seats_taken,
            p.id AS place_id, p.name AS place_name, p.admin1 AS place_admin1, p.country_code AS place_country,
            p.lat AS place_lat, p.lng AS place_lng
            """;

    private final JdbcClient jdbc;

    public DiscoveryRepository(JdbcClient jdbc) {
        this.jdbc = jdbc;
    }

    /**
     * Open adventures of other people, within the radius, overlapping the date window, ordered
     * by start date and then id. Returns up to {@code rowLimit} rows.
     *
     * <ul>
     *   <li>{@code ST_DWithin} on {@code geography} measures in metres on the Earth's surface
     *       and can use the GiST index on {@code location}.
     *   <li>{@code &&} is range overlap; with inclusive bounds, two ranges that share a single
     *       day overlap. It can use the GiST index on {@code trip_dates}.
     *   <li>On {@code text[]}, {@code &&} means "have an element in common". It is checked on
     *       the rows the other two conditions leave over, without an index: with six styles the
     *       filter is not selective, and a GIN index on {@code styles} was measured to slow the
     *       search down (see docs/perf/phase-1-baseline.md).
     *   <li>The row comparison {@code (start_date, id) > (:d, :i)} continues exactly after the
     *       last row of the previous page.
     * </ul>
     *
     * <p>Only the optional parts of the statement vary; no request value is ever concatenated
     * into the SQL.
     *
     * @param earliestStart trips that started before this date are no longer shown
     */
    public List<AdventureCard> search(SearchCriteria criteria, UUID viewerId, LocalDate earliestStart, int rowLimit) {
        StringBuilder sql = new StringBuilder("SELECT ").append(CARD_COLUMNS).append("""
                     , ST_Distance(a.location, q.origin) AS distance_m
                  FROM adventures a
                  JOIN places p ON p.id = a.place_id
                 CROSS JOIN (SELECT ST_SetSRID(ST_MakePoint(:lng, :lat), 4326)::geography AS origin) q
                 WHERE a.status = 'OPEN'
                   AND a.organizer_id <> :viewerId
                   AND a.start_date >= :earliestStart
                   AND ST_DWithin(a.location, q.origin, :radiusMeters)
                   AND a.trip_dates && daterange(:from, :to, '[]')
                """);
        if (criteria.hasStyles()) {
            sql.append("   AND a.styles && CAST(:styles AS text[])\n");
        }
        if (criteria.cursor() != null) {
            sql.append("   AND (a.start_date, a.id) > (:cursorDate, :cursorId)\n");
        }
        sql.append(" ORDER BY a.start_date, a.id\n LIMIT :rowLimit");

        JdbcClient.StatementSpec statement = jdbc.sql(sql.toString())
                .param("lng", criteria.lng())
                .param("lat", criteria.lat())
                .param("viewerId", viewerId)
                .param("earliestStart", earliestStart)
                .param("radiusMeters", criteria.radiusMeters())
                .param("from", criteria.from())
                .param("to", criteria.to())
                .param("rowLimit", rowLimit);
        if (criteria.hasStyles()) {
            statement = statement.param("styles", criteria.styles().toArray(String[]::new));
        }
        if (criteria.cursor() != null) {
            statement = statement
                    .param("cursorDate", criteria.cursor().startDate())
                    .param("cursorId", criteria.cursor().id());
        }
        return statement.query(DiscoveryRepository::toCard).list();
    }

    /**
     * Candidates for matching against the adventure {@code mineId}: open adventures of other
     * people, within the radius of mine and overlapping its dates. The most overlapping and
     * nearest come first, so that the cap drops the least promising rows.
     */
    public List<AdventureCard> matchCandidates(UUID mineId, double radiusMeters, LocalDate earliestStart, int rowLimit) {
        return jdbc.sql("SELECT " + CARD_COLUMNS + """
                             , ST_Distance(a.location, mine.location) AS distance_m
                          FROM adventures mine
                          JOIN adventures a
                            ON a.id <> mine.id
                           AND a.organizer_id <> mine.organizer_id
                           AND a.status = 'OPEN'
                           AND a.start_date >= :earliestStart
                           AND ST_DWithin(a.location, mine.location, :radiusMeters)
                           AND a.trip_dates && mine.trip_dates
                          JOIN places p ON p.id = a.place_id
                         WHERE mine.id = :mineId
                         ORDER BY upper(a.trip_dates * mine.trip_dates) - lower(a.trip_dates * mine.trip_dates) DESC,
                                  distance_m, a.id
                         LIMIT :rowLimit
                        """)
                .param("earliestStart", earliestStart)
                .param("radiusMeters", radiusMeters)
                .param("mineId", mineId)
                .param("rowLimit", rowLimit)
                .query(DiscoveryRepository::toCard)
                .list();
    }

    private static AdventureCard toCard(ResultSet rs, int rowNum) throws SQLException {
        return new AdventureCard(
                rs.getObject("id", UUID.class),
                rs.getObject("organizer_id", UUID.class),
                new PlaceResponse(
                        rs.getLong("place_id"), rs.getString("place_name"), rs.getString("place_admin1"),
                        rs.getString("place_country"), rs.getDouble("place_lat"), rs.getDouble("place_lng")),
                rs.getObject("start_date", LocalDate.class),
                rs.getObject("end_date", LocalDate.class),
                styles(rs.getArray("styles")),
                rs.getString("description"),
                rs.getInt("capacity"),
                rs.getInt("seats_taken"),
                roundToOneDecimal(rs.getDouble("distance_m") / 1000));
    }

    private static List<String> styles(Array array) throws SQLException {
        return List.of((String[]) array.getArray());
    }

    private static double roundToOneDecimal(double value) {
        return Math.round(value * 10) / 10.0;
    }
}
